from datetime import UTC, datetime
from typing import Annotated

import httpx
from fastapi import APIRouter, Depends, Request
from sqlalchemy import Engine, text
from sqlalchemy.exc import SQLAlchemyError

from app.core.config import APP_NAME, APP_VERSION, SERVICE_ID, Settings, get_settings
from app.db.session import check_database, get_engine
from app.schemas.system import DataMode, HealthResponse, ServiceState, ServiceStatus, SystemInfoResponse
from app.simulator.runner import SimulatorRunner

router = APIRouter(tags=["system"])

SettingsDep = Annotated[Settings, Depends(get_settings)]


def get_optional_engine(settings: SettingsDep) -> Engine | None:
    return get_engine() if settings.database_configured else None


EngineDep = Annotated[Engine | None, Depends(get_optional_engine)]


def inference_status() -> ServiceStatus:
    """Which ONNX models are installed (files present); they load on first use."""
    from app.vision import disease, recognizer

    names = (["produce recognition"] if recognizer.model_available() else []) + [
        m.name for m in disease.MODELS.values() if disease.model_available(m)
    ]
    total = 1 + len(disease.MODELS)
    if not names:
        return ServiceStatus(key="inference", label="Model inference (ONNX Runtime)", state="not_configured",
                             detail="No model files installed.")  # fmt: skip
    state: ServiceState = "ok" if len(names) == total else "degraded"
    detail = f"{len(names)} of {total} models installed: {', '.join(names)}."
    return ServiceStatus(key="inference", label="Model inference (ONNX Runtime)", state=state, detail=detail)


def auth_status(settings: Settings) -> tuple[ServiceState, str]:
    """Live check: can we load the token signing keys that sign-ins will be verified against?"""
    if settings.jwks_url:
        try:
            res = httpx.get(settings.jwks_url, timeout=2.0)
            res.raise_for_status()
            n = len(res.json().get("keys", []))
        except (httpx.HTTPError, ValueError) as exc:
            return "degraded", f"Supabase Auth unreachable ({type(exc).__name__})."
        if n == 0:
            return "degraded", "Supabase Auth reachable but publishes no signing keys."
        return "ok", f"Supabase Auth reachable; {n} signing key(s)."
    if settings.supabase_jwt_secret:
        return "ok", "Verifying HS256 tokens with the configured secret."
    return "not_configured", "Set SUPABASE_URL to enable sign-in."


@router.get("/health", response_model=HealthResponse, summary="Liveness check")
def health() -> HealthResponse:
    """Process liveness only; deliberately does not touch the database."""
    return HealthResponse(status="ok", service=SERVICE_ID, version=APP_VERSION, timestamp=datetime.now(UTC))


def data_mode(engine: Engine | None) -> DataMode:
    """Derived from the sensors that actually exist, never assumed."""
    counts: dict[str, int] = {}
    if engine is not None:
        try:
            with engine.connect() as conn:
                rows = conn.execute(
                    text("SELECT source, count(*) FROM sensors WHERE status = 'active' GROUP BY source")
                ).all()
            counts = {str(r[0]): int(r[1]) for r in rows}
        except SQLAlchemyError:
            counts = {}
    sim, hw = counts.get("simulated", 0), counts.get("hardware", 0)
    if sim and hw:
        return DataMode(
            sensors="mixed",
            note=f"{hw} hardware and {sim} simulated sensor(s). Simulated readings are labelled as such.",
        )
    if sim:
        return DataMode(
            sensors="simulated",
            note=(
                f"{sim} simulated sensor(s). Their readings are generated by the AGRI-SENSE simulator and "
                "labelled simulated. No physical hardware is connected."
            ),
        )
    if hw:
        return DataMode(sensors="hardware", note=f"{hw} hardware sensor(s) registered.")
    return DataMode(sensors="none", note="No sensors registered yet.")


def simulator_service(settings: Settings, runner: SimulatorRunner | None) -> ServiceStatus:
    label = "Sensor simulator"
    if runner is None:
        detail = (
            "Disabled (SIMULATOR_ENABLED=false)." if not settings.simulator_enabled else "Needs a database."
        )
        return ServiceStatus(key="simulator", label=label, state="not_configured", detail=detail)
    st = runner.status()
    if st["last_error"]:
        return ServiceStatus(
            key="simulator", label=label, state="degraded", detail=f"Last tick failed: {st['last_error']}."
        )
    state: ServiceState = "ok" if st["running"] else "degraded"
    detail = f"Every {st['interval_seconds']:g} s; {st['last_tick_readings']} reading(s) in the last tick."
    return ServiceStatus(key="simulator", label=label, state=state, detail=detail)


def weather_service(engine: Engine | None) -> ServiceStatus:
    """Reports the newest stored Open-Meteo fetch; does not call Open-Meteo itself."""
    last = None
    if engine is not None:
        try:
            with engine.connect() as conn:
                last = conn.execute(text("SELECT max(fetched_at) FROM weather_data")).scalar()
        except SQLAlchemyError:
            last = None
    if last is None:
        return ServiceStatus(
            key="weather", label="Weather (Open-Meteo)", state="ok", detail="Ready; no forecast fetched yet."
        )
    return ServiceStatus(
        key="weather",
        label="Weather (Open-Meteo)",
        state="ok",
        detail=f"Last forecast fetched {last:%Y-%m-%d %H:%M} UTC.",
    )


@router.get("/system/info", response_model=SystemInfoResponse, summary="Service inventory and data mode")
def system_info(request: Request, settings: SettingsDep, engine: EngineDep) -> SystemInfoResponse:
    """Report what is actually wired up. Every state comes from a live check."""
    db = check_database(engine)
    auth_state, auth_detail = auth_status(settings)
    broadcaster = request.app.state.broadcaster
    runner = getattr(request.app.state, "simulator", None)
    return SystemInfoResponse(
        name=APP_NAME,
        version=APP_VERSION,
        environment=settings.app_env,
        api_prefix=settings.api_prefix,
        data_mode=data_mode(engine) if db.state != "not_configured" else data_mode(None),
        services=[
            ServiceStatus(key="api", label="REST API (FastAPI)", state="ok", detail="Serving requests."),
            ServiceStatus(key="database", label="PostgreSQL", state=db.state, detail=db.detail),
            ServiceStatus(key="auth", label="Supabase Auth", state=auth_state, detail=auth_detail),
            simulator_service(settings, runner),
            ServiceStatus(
                key="realtime",
                label="Sensor stream (SSE)",
                state="ok",
                detail=f"{broadcaster.subscriber_count} live connection(s).",
            ),
            weather_service(engine),
            inference_status(),
        ],
    )
