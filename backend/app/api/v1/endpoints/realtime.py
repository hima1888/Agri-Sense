"""Live sensor stream (SSE) and simulator controls."""

from datetime import UTC, datetime, timedelta
from typing import Annotated, Any

from fastapi import APIRouter, Depends, Request
from fastapi.concurrency import run_in_threadpool
from fastapi.responses import StreamingResponse
from pydantic import Field
from sqlalchemy import select

from app.api.auth import CurrentUser
from app.api.deps import DbSession
from app.models import Sensor
from app.models.enums import SensorType
from app.realtime.broadcaster import Broadcaster
from app.realtime.sse import event_stream
from app.schemas.common import InputModel, OutputModel
from app.schemas.iot import DeviceRead, SensorRead
from app.services import access
from app.services import readings as readings_service
from app.simulator.engine import SimulatorEngine
from app.simulator.provisioning import provision_zone
from app.simulator.runner import SimulatorRunner

router = APIRouter()


def get_broadcaster(request: Request) -> Broadcaster:
    broadcaster: Broadcaster = request.app.state.broadcaster
    return broadcaster


def get_runner(request: Request) -> SimulatorRunner | None:
    runner: SimulatorRunner | None = getattr(request.app.state, "simulator", None)
    return runner


BroadcasterDep = Annotated[Broadcaster, Depends(get_broadcaster)]
RunnerDep = Annotated[SimulatorRunner | None, Depends(get_runner)]


# --- schemas ---------------------------------------------------------------
class ProvisionBody(InputModel):
    sensor_types: list[SensorType] | None = Field(
        default=None, min_length=1, description="Defaults to all 12 supported sensor types."
    )


class ProvisionResult(OutputModel):
    device: DeviceRead
    sensors: list[SensorRead]


class BackfillBody(InputModel):
    hours: int = Field(default=24, ge=1, le=168)
    step_minutes: int = Field(default=10, ge=5, le=60)


class BackfillResult(OutputModel):
    inserted: int
    sensors: int
    start: datetime
    end: datetime
    step_minutes: int


class SimulatorStatus(OutputModel):
    enabled: bool
    running: bool
    interval_seconds: float | None
    last_tick_at: datetime | None
    last_error: str | None
    simulated_sensors: int
    live_connections: int
    note: str


# --- simulator -------------------------------------------------------------
@router.post(
    "/zones/{zone_id}/simulator/provision",
    response_model=ProvisionResult,
    status_code=201,
    tags=["simulator"],
)
def provision(zone_id: int, body: ProvisionBody, user: CurrentUser, db: DbSession) -> dict[str, Any]:
    """Create a simulator device with a full (or chosen) set of simulated sensors in a zone."""
    zone = access.zone_for(db, user, zone_id)
    device, sensors = provision_zone(db, zone, body.sensor_types)
    return {"device": device, "sensors": sensors}


@router.post("/farms/{farm_id}/simulator/backfill", response_model=BackfillResult, tags=["simulator"])
def backfill(
    farm_id: int, body: BackfillBody, user: CurrentUser, db: DbSession, runner: RunnerDep
) -> dict[str, Any]:
    """Generate simulated history for the farm's simulated sensors (idempotent for existing timestamps)."""
    access.farm_for(db, user, farm_id)
    step = timedelta(minutes=body.step_minutes)
    end = datetime.now(UTC).replace(second=0, microsecond=0) - step
    start = end - timedelta(hours=body.hours)
    result = SimulatorEngine(seed=farm_id).backfill(db, farm_id, start, end, step)
    db.commit()
    if runner is not None:
        runner.engine.forget_farm(farm_id)  # live model re-initialises from the new latest values
    return {**result, "start": start, "end": end, "step_minutes": body.step_minutes}


@router.get("/farms/{farm_id}/simulator", response_model=SimulatorStatus, tags=["simulator"])
def simulator_status(
    farm_id: int, user: CurrentUser, db: DbSession, runner: RunnerDep, broadcaster: BroadcasterDep
) -> dict[str, Any]:
    access.farm_for(db, user, farm_id)
    count = len(SimulatorEngine.simulated_sensors(db, farm_id))
    status = runner.status() if runner else {}
    return {
        "enabled": runner is not None,
        "running": bool(status.get("running")),
        "interval_seconds": status.get("interval_seconds"),
        "last_tick_at": status.get("last_tick_at"),
        "last_error": status.get("last_error"),
        "simulated_sensors": count,
        "live_connections": broadcaster.farm_subscriber_count(farm_id),
        "note": (
            "All values from these sensors are generated by the AGRI-SENSE simulator. "
            "No hardware is connected."
        ),
    }


# --- live stream -----------------------------------------------------------
@router.get(
    "/farms/{farm_id}/stream",
    tags=["realtime"],
    response_class=StreamingResponse,
    responses={200: {"content": {"text/event-stream": {}}, "description": "Server-Sent Events"}},
)
async def stream_farm(
    farm_id: int, request: Request, user: CurrentUser, db: DbSession, broadcaster: BroadcasterDep
) -> StreamingResponse:
    """Live readings for one farm as Server-Sent Events.

    Events: `snapshot` (all sensors with their latest reading), then `readings`
    (new values as they are stored), plus `: ping` comments every 10 s so clients can
    detect a dead connection (the web client reconnects after 25 s of silence).
    Authenticate with the usual `Authorization: Bearer` header.
    """

    def load_snapshot() -> dict[str, Any]:
        access.farm_for(db, user, farm_id)
        sensors = db.scalars(select(Sensor).where(Sensor.farm_id == farm_id).order_by(Sensor.id)).all()
        latest = readings_service.latest_per_sensor(db, farm_id)
        snapshot = {
            "farm_id": farm_id,
            "sensors": [
                {
                    "id": s.id,
                    "name": s.name,
                    "zone_id": s.zone_id,
                    "sensor_type": s.sensor_type,
                    "unit": s.unit,
                    "source": s.source,
                    "is_simulated": s.is_simulated,
                    "status": s.status,
                    "min_valid": s.min_valid,
                    "max_valid": s.max_valid,
                    "latest": (
                        {
                            "recorded_at": latest[s.id].recorded_at.isoformat(),
                            "value": latest[s.id].value,
                            "quality": latest[s.id].quality,
                        }
                        if s.id in latest
                        else None
                    ),
                }
                for s in sensors
            ],
        }
        db.close()  # release the DB connection: a stream can stay open for hours
        return snapshot

    snapshot = await run_in_threadpool(load_snapshot)
    queue = broadcaster.subscribe(farm_id)

    async def body() -> Any:
        try:
            async for chunk in event_stream(queue, snapshot, request.is_disconnected):
                yield chunk
        finally:
            broadcaster.unsubscribe(farm_id, queue)

    return StreamingResponse(
        body(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache, no-transform",
            "X-Accel-Buffering": "no",
            "Connection": "keep-alive",
        },
    )
